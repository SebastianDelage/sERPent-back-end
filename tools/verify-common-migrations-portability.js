#!/usr/bin/env node
/*
  ===========================================================================
  PORTABILIDAD DE LAS MIGRACIONES DE db/common
  ===========================================================================

  Corre con:  node tools/verify-common-migrations-portability.js

  QUÉ REVISA
  Que cada .sql de db/common esté escrito en SQL que entiendan LOS DOS motores —PostgreSQL en
  producción y H2 en desarrollo y tests—, porque esos archivos se aplican en los dos sin tener
  una versión por motor. Las reglas son las que están escritas en db/common/README.md; este
  script las hace cumplir en vez de dejarlas como buena intención.

  QUÉ PROBLEMA RESUELVE
  El riesgo de db/common no es el que tenían los dos juegos viejos. Ahí el peligro era que
  divergieran, y de eso se ocupa verificar-paridad-de-migraciones.js. Acá el peligro es otro:
  que alguien escriba un BIGSERIAL o un ON CONFLICT y el archivo funcione perfecto en
  PostgreSQL, pase los tests contra H2 por emulación de MODE=PostgreSQL o directamente falle
  recién en el arranque de producción. Eso no lo detecta ningún test del suite.

  ---------------------------------------------------------------------------
  LO QUE ESTE SCRIPT NO PUEDE HACER, CON NOMBRE Y APELLIDO
  ---------------------------------------------------------------------------

  ES UNA BÚSQUEDA DE TEXTO, NO UN PARSER DE SQL. Nunca levanta una base ni interpreta la
  gramática: busca las construcciones prohibidas que ya sabemos que existen. Consecuencias
  concretas:

    · SOLO ENCUENTRA LO QUE ESTÁ EN LA LISTA. Una construcción de PostgreSQL que no esté
      prevista pasa sin que nadie diga nada. La lista salió de relevar el SQL que este proyecto
      ya tiene; una función exótica que aparezca mañana no está cubierta.

    · NO SABE SI ALGO CORRE. Que no encuentre nada prohibido no prueba que el archivo funcione
      en los dos motores, solo que no usa las formas que ya sabemos que rompen. La prueba de
      verdad es aplicarlo: en H2 lo hace H2MigrationsTest, y en PostgreSQL hace falta correrlo
      a mano porque no hay Docker y por lo tanto no hay Testcontainers.

    · IGNORA LOS COMENTARIOS DE LÍNEA, así que un ejemplo de lo que NO hay que hacer, escrito
      detrás de un "--", no cuenta como hallazgo. Es deliberado: la documentación de un archivo
      tiene que poder nombrar lo que prohíbe.

  POR ESO IMPRIME EL TOTAL RELEVADO, igual que sus hermanas de tools/: archivos leídos y líneas
  de SQL revisadas. Si ese número es cero o cae de golpe, el script se quedó ciego —una carpeta
  movida, un filtro mal escrito— y eso hay que verlo. Un cero en "hallazgos" con cero archivos
  revisados no dice nada.
  ===========================================================================
*/
const fs = require('fs');
const path = require('path');

const COMMON_DIR = path.resolve(__dirname, '../sERPent/src/main/resources/db/common');

/*
  ---------------------------------------------------------------------------
  LAS CONSTRUCCIONES PROHIBIDAS, CADA UNA CON SU REEMPLAZO
  ---------------------------------------------------------------------------
  El reemplazo va acá y no en la documentación suelta porque el mensaje de error tiene que
  decir qué hacer, no solo qué está mal. Quien vea esto en rojo está a mitad de escribir una
  migración y no debería tener que ir a buscar la tabla del README.

  Cada entrada es la MISMA lista que db/common/README.md. Si se agrega una acá, va allá.
*/
const FORBIDDEN = [
  {
    name: 'BIGSERIAL / SERIAL',
    pattern: /\b(BIG)?SERIAL\b/gi,
    replacement: 'BIGINT GENERATED BY DEFAULT AS IDENTITY',
    why: 'es de PostgreSQL; H2 solo lo acepta por emulacion de MODE=PostgreSQL',
  },
  {
    name: 'NOW()',
    pattern: /\bNOW\s*\(\s*\)/gi,
    replacement: 'CURRENT_TIMESTAMP',
    why: 'es de PostgreSQL; CURRENT_TIMESTAMP es estandar y el proyecto ya lo usa',
  },
  {
    name: 'indice parcial (CREATE INDEX ... WHERE)',
    pattern: /CREATE\s+(UNIQUE\s+)?INDEX[\s\S]{0,400}?\bWHERE\b/gi,
    replacement: 'no hay equivalente: va a una carpeta por motor, ver el README',
    why: 'H2 no soporta indices parciales',
  },
  {
    name: 'ON CONFLICT',
    pattern: /\bON\s+CONFLICT\b/gi,
    replacement: 'un UPDATE y un INSERT separados, o MERGE si los dos lo soportan',
    why: 'es de PostgreSQL',
  },
  {
    name: 'ILIKE',
    pattern: /\bILIKE\b/gi,
    replacement: 'LOWER(x) LIKE LOWER(y)',
    why: 'es de PostgreSQL',
  },
  {
    name: 'cast con ::',
    pattern: /::\s*[A-Za-z]/g,
    replacement: 'CAST(x AS tipo)',
    why: 'es de PostgreSQL',
  },
  {
    name: 'COMMENT ON',
    pattern: /\bCOMMENT\s+ON\b/gi,
    replacement: 'un comentario -- en el propio archivo',
    why: 'H2 lo trata distinto y no aporta nada que el archivo no pueda decir',
  },
  {
    name: 'tipos propios de PostgreSQL',
    pattern: /\b(JSONB|JSON|UUID|BYTEA|TSVECTOR|INET|CIDR)\b/gi,
    replacement: 'un tipo que entiendan los dos: VARCHAR, TEXT, BIGINT, NUMERIC',
    why: 'H2 no los tiene, o no con la misma semantica',
  },
  {
    name: 'funciones de fecha propias de PostgreSQL',
    pattern: /\b(DATE_TRUNC|TO_CHAR|AGE|EXTRACT\s*\(\s*EPOCH)\b/gi,
    replacement: 'resolverlo en Java, o usar comparaciones de fecha simples',
    why: 'la sintaxis y el resultado difieren entre motores',
  },
  {
    name: 'ALTER SEQUENCE',
    pattern: /\bALTER\s+SEQUENCE\b/gi,
    replacement: 'ALTER TABLE t ALTER COLUMN c RESTART WITH n, sobre una columna IDENTITY',
    why: 'la secuencia implicita de BIGSERIAL no existe igual en los dos motores',
  },
];

/** Sin comentarios de línea: un ejemplo de lo prohibido, comentado, no es un hallazgo. */
function withoutLineComments(sql) {
  return sql
    .split('\n')
    .map((line) => (line.trim().startsWith('--') ? '' : line))
    .join('\n');
}

/** El número de línea de una posición dentro del texto, para poder ir al lugar. */
function lineAt(text, index) {
  return text.slice(0, index).split('\n').length;
}

if (!fs.existsSync(COMMON_DIR)) {
  console.error('NO EXISTE ' + COMMON_DIR);
  console.error('Si la carpeta se movio o se borro, los locations de los tres perfiles quedan');
  console.error('apuntando a la nada y Flyway no protesta. Ver db/common/README.md.');
  process.exitCode = 1;
  return;
}

const files = fs
  .readdirSync(COMMON_DIR)
  .filter((f) => f.endsWith('.sql'))
  .sort();

const findings = [];
let scannedLines = 0;

for (const file of files) {
  const raw = fs.readFileSync(path.join(COMMON_DIR, file), 'utf8');
  const sql = withoutLineComments(raw);
  scannedLines += sql.split('\n').filter((l) => l.trim().length > 0).length;

  for (const rule of FORBIDDEN) {
    rule.pattern.lastIndex = 0;
    for (const match of sql.matchAll(rule.pattern)) {
      findings.push({
        file,
        line: lineAt(sql, match.index),
        rule,
        text: match[0].replace(/\s+/g, ' ').trim(),
      });
    }
  }
}

console.log('RELEVADO');
console.log('  carpeta            db/common');
console.log('  archivos .sql      ' + files.length);
console.log('  lineas de SQL      ' + scannedLines + '   (sin comentarios ni vacias)');
console.log('  reglas aplicadas   ' + FORBIDDEN.length);
console.log('  hallazgos          ' + findings.length);

/*
  UNA CARPETA SIN NINGÚN .sql NO ES UN ÉXITO, ES UNA CARPETA MUDA. Ya pasó: db/common estuvo
  declarada en los locations de los tres perfiles y vacía, y un arranque de produccion aplicó
  las 32 migraciones viejas y reportó éxito. Nada distinguía eso de que el mecanismo anduviera.
*/
if (files.length === 0) {
  console.log('');
  console.log('CARPETA VACIA');
  console.log('  db/common esta en los locations de los tres perfiles pero no tiene ninguna');
  console.log('  migracion. Flyway aplica lo que encuentra y reporta exito, asi que este estado');
  console.log('  es indistinguible de tener la carpeta mal escrita en la configuracion.');
  console.log('  Tiene que haber al menos V40__common_migrations_start_here.sql.');
  process.exitCode = 1;
  return;
}

if (findings.length) {
  console.log('');
  console.log('NO PORTABLE');
  for (const f of findings) {
    console.log('  ' + f.file + ':' + f.line + '  ' + f.rule.name);
    console.log('      encontrado: ' + f.text);
    console.log('      ' + f.rule.why);
    console.log('      usar: ' + f.rule.replacement);
  }
  console.log('');
  console.log('Si de verdad no se puede escribir portable, va a una carpeta por motor y con el');
  console.log('motivo escrito en el archivo. El procedimiento esta en db/common/README.md.');
}

process.exitCode = findings.length === 0 ? 0 : 1;
